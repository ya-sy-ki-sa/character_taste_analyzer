import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync("docs/詳細設計/11_属性辞書・嗜好集計.md", "utf8");
const section = source.match(/### 2\.2 Initial managed attributes([\s\S]*?)## 3\./u)?.[1];
if (!section) throw new Error("Ontology table was not found");

const attributes = [...section.matchAll(/^\| `([a-z0-9_.-]+)` \| ([^|]+) \| ([a-z_]+) \|$/gmu)].map(
  ([, key, label, category]) => ({ key, label: label.trim(), category }),
);
if (attributes.length < 80) throw new Error(`Ontology is unexpectedly small: ${attributes.length}`);

function uuid(input) {
  const hex = createHash("sha256").update(input).digest("hex");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}

function sql(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function moralValence(key) {
  if (key === "morality.heroic") return "good";
  if (["morality.villainous", "morality.evil", "morality.immoral", "evil.affirms", "evil.enjoys_cruelty"].includes(key))
    return "evil";
  return "neutral";
}

const schemaId = uuid("character-taste:ontology:1.0");
const contentHash = createHash("sha256").update(JSON.stringify(attributes)).digest("hex");
const createdAt = "2026-08-29T00:00:00.000Z";
const lines = [
  "-- Generated from DD-11 by scripts/generate-ontology-migration.mjs.",
  "-- Do not edit this file directly; update DD-11 and regenerate.",
  "",
  "INSERT INTO attribute_schema_versions",
  "  (id, version, status, description, content_hash, published_at, created_at)",
  `VALUES (${sql(schemaId)}, '1.0', 'active', '初期統制語彙', ${sql(contentHash)}, ${sql(createdAt)}, ${sql(createdAt)});`,
  "",
];

for (const attribute of attributes) {
  const id = uuid(`character-taste:attribute:${attribute.key}`);
  lines.push(
    "INSERT INTO attribute_definitions",
    "  (id, schema_version_id, stable_key, category, label, definition, vocabulary_tier, moral_valence, status, created_at)",
    `VALUES (${sql(id)}, ${sql(schemaId)}, ${sql(attribute.key)}, ${sql(attribute.category)}, ${sql(attribute.label)}, ${sql(`${attribute.label}を表す統制属性。`)}, 'managed', ${sql(moralValence(attribute.key))}, 'active', ${sql(createdAt)});`,
    "",
    "INSERT INTO attribute_aliases",
    "  (id, attribute_definition_id, locale, alias, alias_normalized, alias_type, created_at)",
    `VALUES (${sql(uuid(`character-taste:alias:${attribute.key}:ja`))}, ${sql(id)}, 'ja', ${sql(attribute.label)}, ${sql(attribute.label.normalize("NFKC").toLocaleLowerCase("ja-JP"))}, 'surface_form', ${sql(createdAt)});`,
    "",
  );
}

writeFileSync("docs/詳細設計/database/002_seed_ontology_v1.sql", `${lines.join("\n")}\n`);
console.log(`Generated ${attributes.length} ontology attributes`);
