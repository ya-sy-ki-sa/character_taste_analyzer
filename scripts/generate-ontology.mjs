import { createHash } from "node:crypto";
import { darkOntologySeeds } from "../shared/catalogs/dark-ontology.ts";
import { standardOntology } from "../shared/catalogs/ontology.ts";

function uuid(input) {
  const hex = createHash("sha256").update(input).digest("hex");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}
const sql = (value) => `'${String(value).replaceAll("'", "''")}'`;

export function ontologyArtifacts() {
  const artifacts = new Map();
  const standardHash = createHash("sha256")
    .update(
      JSON.stringify(standardOntology.map(({ stableKey, label, category }) => ({ key: stableKey, label, category }))),
    )
    .digest("hex");
  const catalogs = [
    {
      domain: "standard",
      id: uuid("character-taste:ontology:1.0"),
      version: "1.0",
      description: "初期統制語彙",
      hash: standardHash,
      createdAt: "2026-08-29T00:00:00.000Z",
      attributes: standardOntology,
      file: "002_seed_ontology_v1.sql",
    },
    {
      domain: "dark",
      id: "dark-ontology-v1",
      version: "dark-1.0",
      description: "悪・支配・堕落・敵対状態に限定したダークキャラ嗜好ラボ専用Ontology",
      hash: "dark-ontology-v1",
      createdAt: "2026-08-31T00:00:00.000Z",
      attributes: darkOntologySeeds,
      file: "003_seed_dark_ontology.sql",
    },
  ];
  const document = [
    "# 現行の属性辞書",
    "",
    "この一覧は型付きカタログから生成します。変更は shared/catalogs の定義に行ってください。",
    "",
  ];
  for (const catalog of catalogs) {
    const keys = catalog.attributes.map((attribute) => attribute.stableKey);
    if (new Set(keys).size !== keys.length) throw new Error(`Duplicate ontology key: ${catalog.domain}`);
    const lines = [
      "-- Generated by npm run assets:generate from shared/catalogs. Do not edit.",
      "INSERT INTO attribute_schema_versions (id,version,status,description,content_hash,published_at,created_at,analysis_domain)",
      `VALUES (${[catalog.id, catalog.version, "active", catalog.description, catalog.hash, catalog.createdAt, catalog.createdAt, catalog.domain].map(sql).join(",")});`,
      "",
    ];
    document.push(
      `## ${catalog.domain} (${catalog.attributes.length}件)`,
      "",
      "| キー | ラベル | カテゴリ | 定義 |",
      "| --- | --- | --- | --- |",
    );
    for (const attribute of catalog.attributes) {
      const id =
        catalog.domain === "dark"
          ? `dark:${attribute.stableKey}`
          : uuid(`character-taste:attribute:${attribute.stableKey}`);
      lines.push(
        "INSERT INTO attribute_definitions (id,schema_version_id,stable_key,category,label,definition,vocabulary_tier,moral_valence,status,created_at)",
        `VALUES (${[id, catalog.id, attribute.stableKey, attribute.category, attribute.label, attribute.definition, "managed", attribute.moralValence ?? "neutral", "active", catalog.createdAt].map(sql).join(",")});`,
        "",
      );
      document.push(
        `| \`${attribute.stableKey}\` | ${attribute.label} | ${attribute.category} | ${attribute.definition} |`,
      );
    }
    document.push("");
    artifacts.set(`database/migrations/${catalog.file}`, `${lines.join("\n")}\n`);
  }
  artifacts.set("docs/generated/ontology.md", `${document.join("\n")}\n`);
  return artifacts;
}
