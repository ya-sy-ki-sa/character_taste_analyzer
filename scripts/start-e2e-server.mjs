import { spawn, spawnSync } from "node:child_process";
import {
  chmodSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

const markerPath = join(process.cwd(), ".wrangler", "e2e-state-path");
const offlineVarsPath = join(process.cwd(), ".dev.vars.offline");
const offlineVarsHeader = "# Generated by scripts/start-e2e-server.mjs; do not edit.\n";
mkdirSync(dirname(markerPath), { recursive: true });

function readAuthPepper() {
  const fromEnvironment = process.env.AUTH_PEPPER?.trim();
  if (fromEnvironment) return fromEnvironment;
  if (!existsSync(".dev.vars")) throw new Error("AUTH_PEPPER is required for offline E2E");

  const line = readFileSync(".dev.vars", "utf8")
    .split(/\r?\n/u)
    .find((entry) => /^(?:export\s+)?AUTH_PEPPER=/u.test(entry));
  const value = line?.replace(/^(?:export\s+)?AUTH_PEPPER=/u, "").trim();
  if (!value) throw new Error("AUTH_PEPPER is required for offline E2E");
  return value.replace(/^(['"])(.*)\1$/u, "$2");
}

function prepareOfflineVars() {
  if (existsSync(offlineVarsPath)) {
    const existing = readFileSync(offlineVarsPath, "utf8");
    if (!existing.startsWith(offlineVarsHeader))
      throw new Error(".dev.vars.offline exists and is not managed by the E2E launcher");
    unlinkSync(offlineVarsPath);
  }
  writeFileSync(offlineVarsPath, `${offlineVarsHeader}AUTH_PEPPER=${JSON.stringify(readAuthPepper())}\n`, {
    mode: 0o600,
  });
  chmodSync(offlineVarsPath, 0o600);

  return () => {
    if (existsSync(offlineVarsPath) && readFileSync(offlineVarsPath, "utf8").startsWith(offlineVarsHeader))
      unlinkSync(offlineVarsPath);
  };
}

function removeState(path) {
  const resolved = String(path).trim();
  const prefix = join(tmpdir(), "character-taste-e2e-");
  if (!resolved.startsWith(prefix) || resolved.slice(prefix.length).includes("/"))
    throw new Error(`Refusing to remove unexpected E2E state path: ${resolved}`);
  rmSync(resolved, { recursive: true, force: true });
}
if (existsSync(markerPath)) {
  removeState(readFileSync(markerPath, "utf8"));
  unlinkSync(markerPath);
}
const restoreOfflineVars = prepareOfflineVars();
const statePath = mkdtempSync(join(tmpdir(), "character-taste-e2e-"));
writeFileSync(markerPath, `${statePath}\n`, { mode: 0o600 });
const npmCommand = process.platform === "win32" ? "npx.cmd" : "npx";

let cleaned = false;
function cleanup() {
  if (cleaned) return;
  cleaned = true;
  restoreOfflineVars();
  removeState(statePath);
  if (existsSync(markerPath)) unlinkSync(markerPath);
}

const migration = spawnSync(
  npmCommand,
  [
    "wrangler",
    "d1",
    "migrations",
    "apply",
    "character-taste-lab-current-local",
    "--local",
    "--env",
    "offline",
    "--persist-to",
    statePath,
    "--config",
    "wrangler.jsonc",
  ],
  { stdio: "inherit", env: { ...process.env, CLOUDFLARE_ENV: "offline" } },
);
if (migration.status !== 0) {
  cleanup();
  process.exit(migration.status ?? 1);
}

const server = spawn(npmCommand, ["vite", "--host", "127.0.0.1", "--port", "41737", "--strictPort"], {
  stdio: "inherit",
  env: { ...process.env, CLOUDFLARE_ENV: "offline", E2E_STATE_PATH: statePath },
});

let stopping = false;
function stop(signal) {
  if (stopping) return;
  stopping = true;
  server.kill(signal);
  cleanup();
}
process.on("SIGINT", () => stop("SIGINT"));
process.on("SIGTERM", () => stop("SIGTERM"));
process.on("exit", cleanup);
server.on("exit", (code, signal) => {
  cleanup();
  if (signal) process.kill(process.pid, signal);
  else process.exit(code ?? 0);
});
