export const darkOntologySeeds: DarkOntologySeed[] = concepts.flatMap(([group, category, values]) =>
  values.map((value) => {
    const [key, label] = value.split(":") as [string, string];
    return {
      stableKey: `dark.${group}.${key}` as const,
      category,
      label,
      definition: `${label}が、悪・支配・堕落・敵対などのダーク文脈で確認できる場合に用いる。一般的特徴だけには用いない。`,
    };
  }),
);

export const darkOntologyByKey = new Map(darkOntologySeeds.map((item) => [item.stableKey, item]));
