import type { AnalysisDomain } from "../../../shared/analysis-domain";

const ATTRIBUTE_NAMING_INSTRUCTION = `[DEFINITIONS:ATTRIBUTE]
- 評価対象 := 好意・苦手またはその仮説が向けられる性質・行動・状態・関係・変化・意匠。
- 属性の単位 := 別のキャラクターでも比較・集計できる最小の評価対象。
- 複合属性 := 結びつき自体が評価対象となる一つの関係・変化・落差。「基本属性＋付与属性」程度を許容する。
- 適用条件 := 評価が成立する人物・場面・時期等の範囲。条件の存在だけでは、その条件への独立した好意を意味しない。

[DEFINITIONS:SEMIOTICS]
以下は記号論の観点を属性命名へ適用するための作業定義とする。
- 記号媒体 := 意味を担う具体的な形・色・衣装・装身具・口調等の表現。
- 文脈上の意味 := その表現が資料またはユーザー解釈の中で示す帰属・支配・連続性等。
- 意味作用 := 記号媒体が特定の文脈で特定の意味を示す関係。
- 記号媒体そのもの／文脈上の意味／両者の結びつきのどれが評価対象かを区別する。
- 意味の根拠と、その意味への評価の根拠を分離する。評価の確定・仮説の許容範囲は各処理の規則に従う。
- 一般的な象徴連想だけで意味を付与しない。記号媒体の一致だけで意味の一致を推定しない。
- 専門概念は判断に使用し、属性名は比較可能で分かりやすい日本語の一般概念とする。

[PROCEDURE:ATTRIBUTE_NAMING]
1. 評価対象と背景・適用条件・反応を分離する。同一文中の併記や同一人物による保有だけを理由に統合しない。
2. 並列の独立要素は原則分割する。組合せ限定がなければ一体扱いしない。単に登場する要素をすべて評価対象にしない。
3. 背景・適用条件・反応は各処理の対応項目へ移す。条件だけを理由に複合属性や独立した好意を作らない。
4. 関係・変化・落差そのものが対象なら、結びつきをrawLabelに保持する。主客・変化の方向・対象を成立させる否定を落とさない。
5. 残った独立要素と不要な条件・反応を再点検する。一つの関係・変化・落差として説明できない複合属性は分割する。
6. 同じ根拠だけで複合属性と構成要素を重複追加しない。分割要素へ元の評価を無条件にコピーしない。独立した評価が別にある場合のみ区別して扱う。

[INVARIANTS:ATTRIBUTE_NAMING]
- 意味・粒度・評価範囲の保持を、短文化や広い概念への集約より優先する。
- rawLabelに作品固有の固有名詞を含めない。作品名・キャラクター名・別名・組織名・地名・技名・道具名・装備名・固有の形態名を含む。
- 伏字・イニシャル・「その人物」への置換ではなく、支持される一般概念へ抽象化する。
- rawLabelに場面の説明文や「〜が好き」という反応文を使わない。
- attributeStableKeyは同じ概念・粒度の許可済み辞書キーのみ。同義概念は表記を揃え、異なる概念を広いキーへ押し込まない。

[BOUNDARY_EXAMPLES:ATTRIBUTE]
- 「好戦的・嗜虐的・傲慢な態度」→ 好戦性／嗜虐性／傲慢さ。
- 「傲慢な人物が従属させられる落差」→ 傲慢な人物の従属化。傲慢さ単独や従属全般へ分解しない。
- 「恐怖を抱えながら仲間に関わる」→ 恐怖と関与の結びつきを保持。恐怖単独へ拡張しない。
- 「改心しない」→ 否定を保持。改心へ反転しない。`;

const STANDARD_ATTRIBUTE_INSTRUCTION = `[DOMAIN:STANDARD_ATTRIBUTE]
- 身体的特徴（銀髪・長髪・暗い体色等）と服装・装身具（チャイナ服・制服・バイザー等）も単独の属性として扱う。
- 記号媒体そのものへの評価を保持し、象徴的意味の存在を抽出条件にしない。
- 「銀髪でチャイナ服を着た傲慢な人物」が並列の好みで組合せ限定なし → 銀髪／チャイナ服／傲慢さ。
- 「美しさ」「外見」だけへ集約しない。銀髪を美しさ、衣装を性格へ対応づけない。`;

const DARK_ATTRIBUTE_INSTRUCTION = `[DOMAIN:DARK_ATTRIBUTE]
- 一般的特徴を捨象し、ダークな意味を持つ最小単位を扱う。元からの悪・非道徳性、支配・堕落・敵対・変化差分を対象とする。
- 銀髪・チャイナ服・黒色・制服・知性等を単独属性にしない。対象の描写とダーク文脈の結びつきを必要とする。
- 悪役が持つという理由だけで「悪役的」を付加しない。黒色から悪、首輪から従属を自動推定しない。
- ダークな意味を成立させる修飾はrawLabelに保持する。同じダーク場面にあるだけの独立要素は分割する。

[BOUNDARY_EXAMPLES:DARK_ATTRIBUTE]
- 「従属を示す意匠」→ 結びつきを保持。「意匠」にして従属を背景へ移さず、制服・黒色にも分割しない。
- 「洗脳・配下化という支配行動」→ 精神支配／従属化。支配する側とされる側を保持。
- 「敵側のユニフォームと支配を示すデザイン」の両方が対象 → 敵対陣営への帰属を示す意匠／従属を示す意匠。
- 「黒いコスチュームと黒いバイザー」の共通の黒色が悪役性を示し、そこが対象 → 暗色を基調とした悪役的意匠。同じ意味の衣装・装身具を数える目的で属性を増やさない。
- 「闇を象徴する暗い体の色」→ 闇を象徴する身体表現。
- 「希望や友情を象徴していた力が支配や破壊に使われる転用」の両方に好意 → 肯定的な力の支配への転用／肯定的な力の破壊への転用。支配を破壊へ集約せず、友情・支配・破壊単独への好意を作らない。
- 「変化前の口調・技・戦い方が残る落差」が同じ対比の具体例 → 本来の面影を残した変貌。
- 「洗脳によって敵陣営につくこと」自体が対象 → 意思を奪われた敵対化。
- 口調等の面影が残る → 自由意思・自我の保持は未確定。面影を自我の保持の辞書キーへ対応づけない。`;

// Naming only: evidence requirements and output fields belong to extraction or hypothesis prompts.
export function preferenceAttributeInstruction(domain: AnalysisDomain): string {
  return `${ATTRIBUTE_NAMING_INSTRUCTION}\n${domain === "dark" ? DARK_ATTRIBUTE_INSTRUCTION : STANDARD_ATTRIBUTE_INSTRUCTION}`;
}
